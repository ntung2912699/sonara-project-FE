function readPreferences() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY) || '{}');
    return {
      language: saved.language === 'vi' ? 'vi' : 'en',
      theme: saved.theme === 'dark' ? 'dark' : 'light',
    };
  } catch {
    return { language: 'en', theme: 'light' };
  }
}

export function PreferencesProvider({ children }) {
  const [preferences, setPreferences] = useState(readPreferences);

  useEffect(() => {
    document.documentElement.lang = preferences.language;
    document.documentElement.dataset.theme = preferences.theme;
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(preferences));
    } catch (error) {
      console.error('Unable to save display preferences.', error);
    }
  }, [preferences]);

  const value = useMemo(() => ({
    ...preferences,
    setLanguage: (language) => setPreferences((current) => ({ ...current, language })),
    toggleTheme: () => setPreferences((current) => ({
      ...current,
      theme: current.theme === 'dark' ? 'light' : 'dark',
    })),
    t: (text) => preferences.language === 'vi' ? (VI_TRANSLATIONS[text] || text) : text,
  }), [preferences]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const context = useContext(PreferencesContext);
  if (!context) throw new Error('usePreferences must be used within PreferencesProvider.');
  return context;
}
